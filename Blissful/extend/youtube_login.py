"""Optional interactive YouTube login backed by a Selenium browser sidecar.

The sidecar is only present when the ``youtube-login`` compose profile is
enabled. Blissful keeps a single WebDriver session open so the user can sign
in through noVNC, then exports those cookies into the existing masked
``youtube_cookies`` setting used by yt-dlp.
"""
import logging
import os
import threading
import time

import requests

try:  # Selenium is optional; the app must run without the sidecar installed.
    from selenium import webdriver
    from selenium.webdriver.chrome.options import Options
except ImportError:  # pragma: no cover - exercised only without selenium
    webdriver = None
    Options = None

logger = logging.getLogger(__name__)

_LOGIN_REQUIRED = False
_LOCK = threading.RLock()
_DRIVER = None
_LAST_USED = 0.0
_SESSION_TTL = 45 * 60  # close an abandoned login browser after 45 minutes


def mark_relogin_required():
    global _LOGIN_REQUIRED
    with _LOCK:
        _LOGIN_REQUIRED = True


def clear_relogin_required():
    global _LOGIN_REQUIRED
    with _LOCK:
        _LOGIN_REQUIRED = False


def is_relogin_required():
    with _LOCK:
        return _LOGIN_REQUIRED


def cookies_to_netscape(cookies):
    """Convert Selenium cookie dicts to a Netscape cookies.txt document."""
    lines = ['# Netscape HTTP Cookie File',
             '# Generated by Blissful - keep this file private']
    for cookie in cookies or []:
        if not cookie.get('name'):
            continue
        domain = cookie.get('domain') or ''
        flag = 'TRUE' if domain.startswith('.') else 'FALSE'
        path = cookie.get('path') or '/'
        secure = 'TRUE' if cookie.get('secure') else 'FALSE'
        expiry = cookie.get('expiry') or 0
        try:
            expiry = int(expiry)
        except (TypeError, ValueError):
            expiry = 0
        lines.append('\t'.join((domain, flag, path, secure, str(expiry),
                                str(cookie['name']), str(cookie.get('value') or ''))))
    return '\n'.join(lines) + '\n'


class YouTubeLoginService:
    def __init__(self, selenium_url=None, profile_dir=None, novnc_port=None):
        self.selenium_url = (selenium_url or os.environ.get('SELENIUM_URL')
                             or 'http://youtube-login:4444').rstrip('/')
        self.profile_dir = (profile_dir or os.environ.get('YOUTUBE_BROWSER_PROFILE')
                            or '/home/seluser/.config/google-chrome')
        self.novnc_port = str(novnc_port or os.environ.get('YOUTUBE_NOVNC_PORT')
                              or '7900')

    def available(self):
        try:
            response = requests.get(self.selenium_url + '/status', timeout=2)
            return response.ok
        except Exception:
            return False

    def novnc_url(self, request_host=None):
        explicit = os.environ.get('YOUTUBE_NOVNC_URL')
        if explicit:
            base_url = explicit
        else:
            host = (request_host or '').split(':')[0] or 'localhost'
            base_url = f'http://{host}:{self.novnc_port}/'
        # The stock noVNC page shows a Connect dialog with a password field
        # unless autoconnect is set. Skip it so the embedded window goes
        # straight to the browser running on the server.
        separator = '&' if '?' in base_url else '?'
        return f'{base_url}{separator}autoconnect=1&resize=scale'

    @staticmethod
    def _chrome_options():
        """Build Chrome options that Google treats as a normal browser.

        Selenium's default ``enable-automation`` switch and AutomationControlled
        blink feature make Google refuse sign-in with "This browser or app may
        not be secure". Remove both, and keep the window size aligned with the
        noVNC screen in docker-compose.yml.
        """
        options = Options()
        options.add_argument('--no-sandbox')
        options.add_argument('--disable-dev-shm-usage')
        options.add_argument('--disable-gpu')
        options.add_argument('--no-first-run')
        options.add_argument('--no-default-browser-check')
        options.add_argument('--disable-blink-features=AutomationControlled')
        options.add_argument('--window-size=1280,900')
        options.add_experimental_option('excludeSwitches', ['enable-automation'])
        options.add_experimental_option('useAutomationExtension', False)
        return options

    def _close(self):
        global _DRIVER
        driver = _DRIVER
        _DRIVER = None
        if driver is not None:
            try:
                driver.quit()
            except Exception:
                logger.debug('Could not close YouTube login browser')

    def status(self):
        global _DRIVER, _LAST_USED
        with _LOCK:
            if _DRIVER is not None and time.time() - _LAST_USED > _SESSION_TTL:
                self._close()
            cookie_count = 0
            if _DRIVER is not None:
                try:
                    cookie_count = len(_DRIVER.get_cookies())
                    _LAST_USED = time.time()
                except Exception:
                    self._close()
            return {
                'available': self.available(),
                'active': _DRIVER is not None,
                'cookie_count': cookie_count,
                'relogin_required': is_relogin_required(),
            }

    def start(self):
        global _DRIVER, _LAST_USED
        with _LOCK:
            if webdriver is None or Options is None:
                return {'success': False,
                        'error': 'selenium package is not installed'}
            if not self.available():
                return {'success': False,
                        'error': 'YouTube login browser is not running. '
                                 'Start it with: docker compose --profile '
                                 'youtube-login up -d youtube-login'}
            if _DRIVER is None:
                # No persistent Chrome profile: cookies are exported to
                # Blissful's config on finish and reused by yt-dlp.
                options = self._chrome_options()
                try:
                    _DRIVER = webdriver.Remote(
                        command_executor=self.selenium_url,
                        options=options)
                    _DRIVER.get('https://www.youtube.com')
                except Exception as exc:
                    _DRIVER = None
                    logger.warning('Could not start YouTube login browser: %s', exc)
                    return {'success': False, 'error': str(exc)}
            _LAST_USED = time.time()
            return {'success': True, 'active': True}

    def finish(self, config_manager):
        global _DRIVER
        with _LOCK:
            if _DRIVER is None:
                return {'success': False, 'error': 'No active login session'}
            try:
                cookies = _DRIVER.get_cookies()
            except Exception as exc:
                return {'success': False, 'error': str(exc)}
            youtube_cookies = [c for c in cookies
                               if 'youtube' in (c.get('domain') or '')]
            if not youtube_cookies:
                return {'success': False,
                        'error': 'No YouTube cookies found. Sign in to YouTube '
                                 'in the browser window first.'}
            content = cookies_to_netscape(youtube_cookies)
            config = config_manager.get_config()
            config['youtube_cookies'] = content
            if not config_manager.save_config(config):
                return {'success': False, 'error': 'Could not save cookies'}
            self._close()
            clear_relogin_required()
            return {'success': True, 'cookie_count': len(youtube_cookies)}

    def cancel(self):
        with _LOCK:
            self._close()
            return {'success': True}
