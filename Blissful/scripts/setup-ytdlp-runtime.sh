#!/bin/sh
# Idempotent runtime bootstrap for an older Blissful image that was NOT built
# from this fork.
#
# Both the repo-built and CI-published fork images already contain Deno 2.x,
# yt-dlp>=2026.10.26 and bgutil-ytdlp-pot-provider>=2.0.2. Older images do not,
# so this
# script installs them into a PERSISTENT downloads directory that survives
# container recreation, and writes a matching yt-dlp.conf.
#
# Usage (inside a running container, as root):
#   docker exec -u 0 blissful sh /path/to/setup-ytdlp-runtime.sh
# Or on a host with the downloads directory mounted at YT_DLP_HOME.
#
# All paths/versions are environment-overridable. No secrets are read or
# written. Re-running is safe: completed steps are skipped unless forced.
set -eu

YT_DLP_HOME="${YT_DLP_HOME:-/app/downloads}"
PYLIB_DIR="${PYLIB_DIR:-$YT_DLP_HOME/pylib}"
DENO_BIN="${DENO_BIN:-$YT_DLP_HOME/deno}"
CONF_FILE="${CONF_FILE:-$YT_DLP_HOME/yt-dlp.conf}"
POT_PROVIDER_URL="${POT_PROVIDER_URL:-http://blissful-pot:4416}"
DENO_VERSION="${DENO_VERSION:-v2.9.8}"
YT_DLP_SPEC="${YT_DLP_SPEC:-yt-dlp>=2026.10.26}"
POT_PROVIDER_SPEC="${POT_PROVIDER_SPEC:-bgutil-ytdlp-pot-provider>=2.0.2}"
PYTHON_BIN="${PYTHON_BIN:-python3}"
PUID="${PUID:-1000}"
PGID="${PGID:-1000}"
FORCE_DOWNLOAD="${FORCE_DOWNLOAD:-0}"
FORCE_INSTALL="${FORCE_INSTALL:-0}"
FORCE_CONF="${FORCE_CONF:-0}"

log() { printf '[setup-ytdlp-runtime] %s\n' "$*"; }
die() { printf '[setup-ytdlp-runtime] ERROR: %s\n' "$*" >&2; exit 1; }

mkdir -p "$YT_DLP_HOME" "$PYLIB_DIR"
tmpdir="$(mktemp -d "${TMPDIR:-/tmp}/blissful-ytdlp.XXXXXX")"
trap 'rm -rf "$tmpdir"' EXIT HUP INT TERM

# ---- 1. Deno 2.x into the persistent downloads dir -------------------------
if [ -x "$DENO_BIN" ] && [ "$FORCE_DOWNLOAD" != "1" ]; then
    log "Deno already present: $DENO_BIN ($("$DENO_BIN" --version 2>/dev/null | head -n 1))"
else
    case "$(uname -m)" in
        x86_64|amd64) deno_target="x86_64-unknown-linux-gnu" ;;
        aarch64|arm64) deno_target="aarch64-unknown-linux-gnu" ;;
        *) die "unsupported architecture for Deno: $(uname -m)" ;;
    esac

    deno_url="https://github.com/denoland/deno/releases/download/${DENO_VERSION}/deno-${deno_target}.zip"
    log "Downloading Deno ${DENO_VERSION} (${deno_target})"
    if command -v curl >/dev/null 2>&1; then
        curl -fsSL --retry 3 "$deno_url" -o "$tmpdir/deno.zip" || die "Deno download failed: $deno_url"
    elif command -v wget >/dev/null 2>&1; then
        wget -q -O "$tmpdir/deno.zip" "$deno_url" || die "Deno download failed: $deno_url"
    else
        die "curl or wget is required to download Deno"
    fi

    if command -v unzip >/dev/null 2>&1; then
        unzip -o -j "$tmpdir/deno.zip" -d "$tmpdir" >/dev/null || die "could not unzip Deno archive"
    else
        "$PYTHON_BIN" - "$tmpdir/deno.zip" "$tmpdir" <<'PY' || die "could not extract Deno archive"
import sys, zipfile
src, dst = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(src) as z:
    names = [n for n in z.namelist() if n == 'deno' or n.endswith('/deno')]
    if not names:
        raise SystemExit('deno binary not found in archive')
    with open(dst + '/deno', 'wb') as out:
        out.write(z.read(names[0]))
PY
    fi

    cp "$tmpdir/deno" "$DENO_BIN"
    chmod 0755 "$DENO_BIN"
    log "Installed Deno to $DENO_BIN ($("$DENO_BIN" --version 2>/dev/null | head -n 1))"
fi

# ---- 2. yt-dlp + PO-token provider into persistent pylib -------------------
has_pot_provider() {
    for path in "$PYLIB_DIR"/bgutil*pot*; do
        [ -e "$path" ] && return 0
    done
    return 1
}

if [ -f "$PYLIB_DIR/yt_dlp/__init__.py" ] && has_pot_provider && [ "$FORCE_INSTALL" != "1" ]; then
    log "yt-dlp and PO provider already installed in $PYLIB_DIR"
else
    command -v "$PYTHON_BIN" >/dev/null 2>&1 || die "Python not found: $PYTHON_BIN"
    log "Installing $YT_DLP_SPEC and $POT_PROVIDER_SPEC into $PYLIB_DIR"
    "$PYTHON_BIN" -m pip install --no-cache-dir --upgrade --target "$PYLIB_DIR" \
        "$YT_DLP_SPEC" "$POT_PROVIDER_SPEC" \
        || die "pip install failed"
fi

# ---- 3. yt-dlp.conf pointing at the local Deno and the sidecar -------------
if [ -f "$CONF_FILE" ] && [ "$FORCE_CONF" != "1" ]; then
    log "Keeping existing $CONF_FILE (set FORCE_CONF=1 to regenerate)"
else
    cat > "$CONF_FILE" <<EOF
# Generated by scripts/setup-ytdlp-runtime.sh.
# blissful-pot is the PO-token provider sidecar on the shared Docker network
# (no published host port). Edit this file or use --config-location to override.
--js-runtimes deno:$DENO_BIN
--extractor-args youtubepot-bgutilhttp:base_url=$POT_PROVIDER_URL
EOF
    log "Wrote $CONF_FILE"
fi

if [ "$(id -u)" -eq 0 ]; then
    chown -R "${PUID}:${PGID}" "$YT_DLP_HOME"
fi

log "Done. Verify with: curl -s http://localhost:7373/api/health"
log "Note: PO tokens reduce 403s but do not guarantee they never happen."
